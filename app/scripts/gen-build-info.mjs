// Generates generated/build-info.ts before each build/deploy (see
// wrangler.jsonc build.command). Uses Workers Builds env vars when
// present, falls back to local git, then to "unknown".
// --check flag: print the build-info JSON to stdout WITHOUT writing generated/build-info.ts, then exit 0
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

const buildInfo = {
  commit: process.env.WORKERS_CI_COMMIT_SHA || git("git rev-parse HEAD") || "unknown",
  branch: process.env.WORKERS_CI_BRANCH || git("git branch --show-current") || "unknown",
  buildTime: new Date().toISOString(),
  builder: process.env.WORKERS_CI ? "workers-builds" : "local",
};

if (process.argv.includes("--check")) {
  console.log(JSON.stringify(buildInfo, null, 2));
  process.exit(0);
}

const out = join(root, "generated", "build-info.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/gen-build-info.mjs — do not edit.\nexport const BUILD_INFO = ${JSON.stringify(buildInfo, null, 2)} as const;\n`,
);
console.log(`build-info: ${buildInfo.commit.slice(0, 7)}@${buildInfo.branch} (${buildInfo.builder})`);
